import { COUNTRY_DERIVED } from './countries.data';
import { HOUSE_TYPES } from './types';
import type { Assumptions } from './types';

/**
 * Reference values per CIRCUS partner country.
 *
 * The Netherlands keeps the Excel workbook's values. For the other countries a
 * value is the Dutch workbook value times the ratio of the same public EU
 * indicator for that country and for the Netherlands (Eurostat, PVGIS), so the
 * workbook's Dutch house types and level are kept. Monthly patterns for
 * heating, solar and wind come from the country's own data. Values without a
 * country source stay Dutch and say so. Raw indicators: countries.data.ts
 * (generated by scripts/country-data.mjs). Texts: `profile.sources` strings.
 */
export const COUNTRIES = ['nl', 'be', 'de', 'fr', 'ie'] as const;
export type CountryId = (typeof COUNTRIES)[number];
export const DEFAULT_COUNTRY: CountryId = 'nl';

/** Where a reference value comes from; each id has a text under `profile.sources.kinds`. */
export const SOURCE_KINDS = [
  'workbook',
  'technical',
  'roof',
  'eurostat-electricity',
  'eurostat-heat',
  'pvgis',
  'degree-days',
  'wind-monthly',
  'car-km',
  'dutch-only',
] as const;
export type SourceKind = (typeof SOURCE_KINDS)[number];

/**
 * Average distance driven per passenger car and year, from each country's own
 * statistics (methods differ; texts under `profile.sourcesPage.car`). `null` =
 * no source confirmed: the Dutch workbook value is used and marked as such.
 * Checked 2026-11-23.
 */
export const CAR_KM: Record<Exclude<CountryId, 'nl'>, { km: number; year: string; url: string } | null> = {
  // Car-Pass annual report 2025 (national odometer register).
  be: { km: 14172, year: '2025', url: 'https://www.car-pass.be/public/files/8952_CAP_Jaarverslag-2025_ENG_v5bis-Interactief.pdf' },
  // KBA, Verkehr in Kilometern – Inländerfahrleistung, Kurzbericht 2025.
  de: { km: 10616, year: '2025', url: 'https://www.kba.de/DE/Statistik/Kraftverkehr/VerkehrKilometer/vk_inlaenderfahrleistung/2025/2025_vk_kurzbericht.html' },
  // SDES, "40 millions de voitures en circulation en France au 1er janvier 2026" (provisional).
  fr: { km: 11600, year: '2025', url: 'https://www.statistiques.developpement-durable.gouv.fr/40-millions-de-voitures-en-circulation-en-france-au-1er-janvier-2026' },
  // CSO, table THA10 Road Traffic Volumes, average kilometres travelled, private cars.
  ie: { km: 15196, year: '2023', url: 'https://data.cso.ie/table/THA10' },
};

const roundTo = (value: number, step: number) => Math.round(value / step) * step;

/** The reference values of a country, built from the Dutch workbook values. */
export function countryReference(country: CountryId, nl: Assumptions): Assumptions {
  if (country === 'nl') return nl;
  const data = COUNTRY_DERIVED[country];
  const car = CAR_KM[country];
  const houses = Object.fromEntries(
    HOUSE_TYPES.map((type) => [
      type,
      {
        electricityKwh: roundTo(nl.houses[type].electricityKwh * data.electricityFactor, 10),
        gasM3: roundTo(nl.houses[type].gasM3 * data.heatFactor, 10),
      },
    ]),
  ) as Assumptions['houses'];
  return {
    ...nl,
    houses,
    kmPerCar: car ? car.km : nl.kmPerCar,
    kwhPerWp: Number((nl.kwhPerWp * data.solarFactor).toFixed(2)),
    seasonality: {
      ...nl.seasonality,
      heating: [...data.heatingSeason],
      solar: [...data.solarSeason],
      wind: [...data.windSeason],
    },
  };
}

const TECHNICAL = new Set([
  'gasKwhPerM3',
  'boilerEfficiency',
  'hybridHeatShare',
  'electricHeatShare',
  'hybridCop',
  'electricCop',
  'evKwhPerKm',
  'panelWp',
]);

/** Where the reference value at a dotted path comes from, for a country. */
export function sourceOf(country: CountryId, path: string): SourceKind {
  const [head, , last] = path.split('.');
  if (head === 'maxPanelsPerHome') return 'roof';
  if (TECHNICAL.has(head)) return 'technical';
  if (country === 'nl') return 'workbook';
  if (head === 'houses') return last === 'gasM3' ? 'eurostat-heat' : 'eurostat-electricity';
  if (head === 'kwhPerWp') return 'pvgis';
  if (head === 'kmPerCar') return CAR_KM[country] ? 'car-km' : 'dutch-only';
  if (head === 'seasonality') {
    const series = path.split('.')[1];
    if (series === 'heating') return 'degree-days';
    if (series === 'solar') return 'pvgis';
    if (series === 'wind') return 'wind-monthly';
  }
  return 'dutch-only';
}
